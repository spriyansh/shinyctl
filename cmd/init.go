package cmd

import (
	"fmt"
	"os"

	"github.com/spf13/cobra"
)

var (
	initOutput         string
	initAppGroup       string
	initAppName        string
	initEntrypointFile string
	initPort           int
	initAppStateFile   string
	initForce          bool
)

const initTemplate = `# Generated by ` + "`shinyctl init`" + ` — edit the values below, then run:
#   shinyctl apply -f %s
# Relative paths resolve from this file's directory.

app-group: %s
app-name: %s
entrypoint-file: %s
port: %d
app-state-file: %s

# Optional fields — uncomment to use:
# host: 0.0.0.0            # address the app's port listens on (default: every interface); 127.0.0.1 = this machine only
# replicas: 1              # copies that serve visitors (1-16)
# warm-replicas: 1         # ready spares that take over when a copy dies (0-16); each copy is an R process
# lb-policy: least-conn    # how new visitors pick a copy: least-conn, round-robin, random, first
# restart-policy: always   # always (default) / on-failure / never
# working-dir: .           # defaults to entrypoint-file's own directory
# env:
#   R_LIBS_USER: /path/to/your/Rlibs
`

var initCmd = &cobra.Command{
	Use:   "init",
	Short: "Scaffold a new app manifest YAML file",

	RunE: func(cmd *cobra.Command, args []string) error {
		if _, err := os.Stat(initOutput); err == nil && !initForce {
			return fmt.Errorf("%q already exists — pass --force to overwrite", initOutput)
		}

		body := fmt.Sprintf(initTemplate,
			initOutput, initAppGroup, initAppName, initEntrypointFile, initPort, initAppStateFile)

		if err := os.WriteFile(initOutput, []byte(body), 0644); err != nil {
			return fmt.Errorf("writing %q: %w", initOutput, err)
		}

		fmt.Printf("Wrote %q — edit it, then run `shinyctl apply -f %s`\n", initOutput, initOutput)
		return nil
	},
}

func init() {
	initCmd.Flags().StringVarP(&initOutput, "output", "o", "./shinyctl.yaml", "path to write the manifest to")
	initCmd.Flags().StringVar(&initAppGroup, "app-group", "my-group", "app-group value")
	initCmd.Flags().StringVar(&initAppName, "app-name", "my-app", "app-name value")
	initCmd.Flags().StringVar(&initEntrypointFile, "entrypoint-file", "./app.R", "entrypoint-file value")
	initCmd.Flags().IntVar(&initPort, "port", 8080, "port value")
	initCmd.Flags().StringVar(&initAppStateFile, "app-state-file", "./state.json", "app-state-file value")
	initCmd.Flags().BoolVar(&initForce, "force", false, "overwrite --output if it already exists")

	rootCmd.AddCommand(initCmd)
}
